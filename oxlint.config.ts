import {
  ANTELOPE_IGNORE_PATTERNS,
  antelopePreset,
} from "@antelopejs/tooling-configs/oxc/lint";
import { defineConfig } from "oxlint";

/**
 * The external-database operations of `@antelopejs/interface-dms-builder`: each
 * takes a database URL, writes one, or opens a connection to one. `Operations`
 * maps every operation by name, these included, and `default` is the module
 * itself.
 */
const CONNECTION_OPERATIONS = [
  "AnalyseDatabase",
  "CheckDatabaseConnection",
  "ConfigureProject",
  "default",
  "GetAnalysis",
  "GetDatabaseConnection",
  "GetDatabaseProject",
  "GetLatestAnalysis",
  "GetMapping",
  "ListDatabaseConnections",
  "ListEntryConnections",
  "MapResources",
  "Operations",
  "PreviewMapResources",
  "RemoveDatabaseConnection",
  "RepairDatabaseConnections",
  "SetDatabaseConnectionUrl",
];

/**
 * Only the owner's connect routes call the external-database operations, so
 * every URL they reach comes from the owner's request, never from the agent.
 */
const OWNER_CONNECT_ROUTES = "src/builder/routes/database.ts";

const OWNER_ONLY_MESSAGE = `Only ${OWNER_CONNECT_ROUTES} calls the external-database operations, so no URL the agent supplies reaches a connection. See "Only the owner supplies a database URL" in docs/8.database-connection.md.`;

/**
 * The Vue layer keeps its own ESLint setup until the front-end migration, the
 * Codex protocol types are generated by
 * `sidecar/scripts/generate-codex-types.mjs`, and the e2e playground's
 * dependencies are installed only by a run's `prepare`.
 */
export default defineConfig({
  extends: [antelopePreset({ importSorting: false })],
  ignorePatterns: [
    ...ANTELOPE_IGNORE_PATTERNS,
    "frontend-vue/**",
    "sidecar/src/providers/codex/protocol/**",
    "e2e/playground/**",
    "e2e/builder/playground/**",
  ],
  options: {
    typeAware: true,
  },
  overrides: [
    {
      files: ["**/*.{ts,mts,cts,js,mjs,cjs}"],
      rules: {
        "no-restricted-imports": [
          "error",
          {
            paths: [
              {
                name: "@antelopejs/interface-dms-builder",
                importNames: CONNECTION_OPERATIONS,
                message: OWNER_ONLY_MESSAGE,
              },
            ],
            patterns: [
              {
                group: ["@antelopejs/interface-dms-builder/*"],
                message: `Import from the package root. ${OWNER_ONLY_MESSAGE}`,
              },
            ],
          },
        ],
      },
    },
    {
      files: ["**/*.{ts,mts,cts}"],
      rules: { "typescript/no-require-imports": "error" },
    },
    {
      files: [OWNER_CONNECT_ROUTES],
      rules: { "no-restricted-imports": ["error", { paths: [] }] },
    },
  ],
});
